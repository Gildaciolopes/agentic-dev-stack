export const guessLang = () => (/^pt/i.test(process.env.LC_ALL || process.env.LANG || Intl.DateTimeFormat().resolvedOptions().locale || "") ? "pt-BR" : "en");
export function t(key, vars = {}) {
  const v = S[LANG][key] ?? S.en[key] ?? key;
  return Array.isArray(v) ? v : String(v).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}
